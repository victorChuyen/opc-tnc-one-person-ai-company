export function getCurrentLang() {
    return localStorage.getItem('tnc-lang') || 'vi';
}

export function setLanguage(lang) {
    if (!['vi', 'en'].includes(lang)) return;
    localStorage.setItem('tnc-lang', lang);
    document.documentElement.setAttribute('lang', lang);

    const dict = translations[lang];
    if (!dict) return;

    // Translate elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = dict[key];
            } else {
                el.innerText = dict[key];
            }
        }
    });

    // Update Mobile Footer Action Link & Target
    const mobActionBtn = document.getElementById('mobile-footer-action-btn');
    if (mobActionBtn && dict["mobile_footer_action_link"]) {
        mobActionBtn.href = dict["mobile_footer_action_link"];
    }

    // Update active button state on language selector
    const btnVi = document.getElementById('lang-btn-vi');
    const btnEn = document.getElementById('lang-btn-en');
    if (btnVi && btnEn) {
        if (lang === 'vi') {
            btnVi.classList.add('active');
            btnEn.classList.remove('active');
        } else {
            btnEn.classList.add('active');
            btnVi.classList.remove('active');
        }
    }
}
